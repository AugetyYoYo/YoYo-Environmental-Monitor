#ifndef _APP_H
#define _APP_H

#include "STC8H.H"
#include "bsp_key.h"

/*==================================================================
  应用层：页面状态机 + 按键事件分发
  ------------------------------------------------------------------
  三个页面，按键操作如下：

        短按 MODE              短按 MODE
   主页 <──────────> 菜单 <────────────── 数据页
    │  长按 MODE = 强制重刷全部数据         │  长按 DN = 回菜单
    │  短按 UP/DN = 无                     │  短按 UP/DN = 翻页
    └──────────────────────────────────────┘

  main.c 只负责初始化和调 app_run()，业务逻辑全在这里。
==================================================================*/

/* 页面编号 */
typedef enum {
    page_home = 0, /* 主页 */
    page_menu,     /* 菜单 */
    page_data      /* 数据查看页 */
} page_id_t;

/* 初始化：画第一屏 */
void app_init(void);

/* 主循环每圈调一次：收 GPS、轮流刷传感器、处理按键、按需重画 */
void app_run(void);

#endif
