#ifndef _BSP_PMS_H
#define _BSP_PMS_H

#include "STC8H.H"

/*==================================================================
  PMS7003 颗粒物（UART3：P5.0/P5.1，9600-8-N-1）
  ------------------------------------------------------------------
  上电默认主动输出，32 字节/帧（200~800ms，平稳模式约 2s）：
    42 4D | 帧长(2) | PM1.0(CF=1) | PM2.5(CF=1) | PM10(CF=1) |
    PM1.0(大气) | PM2.5(大气) | PM10(大气) | 6 组个数(12B) | 版本+错误码(2B) | 校验(2B)
  校验 = 前 30 字节之和（低 16 位）；取"大气环境"值（帧字节 10~15）。

  ★连续数据流必须用接收中断 + 环形缓冲：主循环每圈才轮询一次，
   一个字节能装不下 32 字节的帧，会一直丢字节、校验不过。
==================================================================*/

typedef struct {
    unsigned char ok;   /* 1 = 收到过校验正确的帧 */
    unsigned int pm1_0; /* ug/m3，大气环境值 */
    unsigned int pm2_5;
    unsigned int pm10;
} pms_info_t;

/* 初始化 UART3 + 打开接收中断（硬件没接也能跑，只是永远 ok=0） */
void bsp_pms_init(void);

/* 从环形缓冲取字节拼帧，主循环每圈调一次（非阻塞） */
void bsp_pms_poll(void);

/* 取状态（只读） */
pms_info_t *bsp_pms_get(void);

#endif
